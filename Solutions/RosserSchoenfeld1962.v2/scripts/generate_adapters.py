#!/usr/bin/env python3
"""Reuse v1's kernel-checked witness leaves with a stronger accumulator invariant.

The small-range factor and binary-exponent hints and twelve accumulator endpoints use exact integers.
No numerical truth assertion from this generator is trusted. Each adapter references
an existing proved certificate, applies shifted_sound, and joins adjacent ranges. --check
compares generated text and verifies that every reused RS12 module matches the recorded base.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
V1 = ROOT.parent / 'RosserSchoenfeld1962.v1'
REPO = ROOT.parent.parent
# Canonical v1 source merged in upstream PR #125. No local development refs are needed.
PIN = '6664139ccebea21ecdb9bd94539fc75d77564794'
HEADER = '''/-
Copyright (c) 2026 IEANTN contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Håkon Xue-Lønmo, PNT+ contributors
-/
'''



def small_output():
    # Exact integer data only. Lean rechecks every factor witness, binary power bound,
    # strict prefix comparison, and endpoint; this generator is outside the trust boundary.
    acc = 0
    endpoints = [0]
    units = []
    for n in range(1, 601):
        u = 0
        a, k = 1, 0
        p = next((d for d in range(2, n + 1) if n % d == 0), 1)
        if p > 1:
            m, power = n, 0
            while m % p == 0:
                m //= p
                power += 1
            if m == 1:
                a, k = p, power
                u = (p ** 256).bit_length()
                acc += u
            else:
                a, k = p ** power, 0
        units.append((a, k, u))
        if n % 50 == 0:
            endpoints.append(acc)
    chunks = [HEADER, 'import Max113.SmallChecker\n\n',
              '/-! Generated exact integer endpoints; every block is checked by the kernel. -/\n',
              'namespace RS12Max113\nopen Chebyshev\n',
              'set_option Elab.async false\nset_option maxRecDepth 100000\n',
              'set_option maxHeartbeats 0\n\n']
    previous = '(by simp [Chebyshev.psi])'
    for i in range(12):
        start, end = 50*i, 50*(i+1)
        a, b = endpoints[i:i+2]
        hints = ", ".join(f"({a}, {k}, {u})" for a, k, u in units[start:end])
        chunks.append(f"""private def small_units_{i} : List (ℕ × ℕ × ℕ) := [{hints}]

private theorem small_check_{i} : checkSmall {start} small_units_{i} {a} {b} = true := by
  decide +kernel

private theorem small_block_{i} :
    ψ ({end} : ℕ) ≤ ({b} : ℝ) * 693148 / 256000000 ∧
      (∀ n : ℕ, {start} < n → n ≤ {end} → n ≠ 113 → ψ (n : ℝ) < 1.03882 * n) := by
  have h := checkSmall_sound (start := {start}) (us := small_units_{i})
    (acc := {a}) (target := {b}) small_check_{i} {previous}
  exact h

""")
        previous = f'small_block_{i}.1'
    def join(parts):
        if len(parts) == 1:
            return parts[0]
        mid = len(parts)//2
        return f'(small_join {join(parts[:mid])} {join(parts[mid:])})'
    chunks.append("""/-- Five units of slack recovered at the old finite certificate's seed. -/
theorem psi_600_seed : ψ (600 : ℕ) + 5 ≤ (6919 : ℝ) * 693148 / 8000000 := by
  have h := small_block_11.1
  norm_num at h
  linarith

theorem small_integer {n : ℕ} (hn : 0 < n) (h600 : n ≤ 600) (hne : n ≠ 113) :
    ψ (n : ℝ) < 1.03882 * n :=
  """ + join([f'small_block_{i}.2' for i in range(12)]) + ' n hn h600 hne\n\nend RS12Max113\n')
    return ''.join(chunks)


def outputs():
    result = {'Max113/Small.lean': small_output()}
    certificates = []
    last_end = 600
    num_leaves = 0
    for shard in range(20):
        source = (V1 / f'RS12/PsiData{shard:02}.lean').read_text()
        leaves = re.findall(r'private theorem psi_check_(\d+) : checkWitnessBlock (\d+) psi_hints_\d+ (\d+) (\d+) = true', source)
        assert leaves
        num_leaves += len(leaves)
        previous = 'psi_600_seed' if shard == 0 else f'certificate_{shard-1:02}.1'
        chunks = [HEADER, f'import RS12.PsiData{shard:02}\n',
                  'import Max113.Shifted\n',
                  'import Max113.Small\n' if shard == 0 else f'import Max113.Data{shard-1:02}\n',
                  '\n/-! Generated by scripts/generate_adapters.py; no certificate data is copied. -/\n',
                  'namespace RS12Max113\nopen Chebyshev\nset_option Elab.async false\nset_option maxRecDepth 100000\n\n']
        ranges = []
        lo = last_end
        for start, repeated, acc, target in leaves:
            start = int(start)
            assert start == int(repeated) == last_end
            end = min(start + 250, 500000)
            name = f'block_{start}'
            chunks.append(f'''private theorem {name} :
    ψ ({end} : ℕ) + 5 ≤ ({target} : ℝ) * 693148 / 8000000 ∧
      (∀ m : ℕ, {start} < m → m ≤ {end} → ψ (m : ℕ) + 5 ≤ 1.038829 * m) := by
  have h := shifted_sound (δ := 5)
    (rs12_private% RS12.PsiData{shard:02} RS12PsiInteger.psi_check_{start}) {previous}
  exact ⟨h.1, fun m hlo hhi => h.2 m hlo hhi (by omega)⟩

''')
            previous = name + '.1'
            ranges.append(name + '.2')
            last_end = end
        def join(parts):
            if len(parts) == 1:
                return parts[0]
            mid = len(parts)//2
            return f'(shifted_join {join(parts[:mid])} {join(parts[mid:])})'
        chunks.append(f'''/-- The original witness shard, now carrying the seed's five-unit saving. -/
theorem certificate_{shard:02} :
    ψ ({last_end} : ℕ) + 5 ≤ ({target} : ℝ) * 693148 / 8000000 ∧
      (∀ m : ℕ, {lo} < m → m ≤ {last_end} → ψ (m : ℕ) + 5 ≤ 1.038829 * m) :=
  ⟨{previous}, {join(ranges)}⟩

end RS12Max113
''')
        result[f'Max113/Data{shard:02}.lean'] = ''.join(chunks)
        certificates.append(f'certificate_{shard:02}.2')
    assert last_end == 500000
    assert num_leaves == 1998
    result['Max113/Finite.lean'] = HEADER + '''import Max113.Data19

namespace RS12Max113
open Chebyshev

/-- The complete reused finite range with a five-unit absolute improvement. -/
theorem finite_integer {n : ℕ} (hlo : 600 < n) (hhi : n ≤ 500000) :
    ψ (n : ℕ) + 5 ≤ 1.038829 * n :=
  ''' + join(certificates) + ''' n hlo hhi

end RS12Max113
'''
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    records = []
    for path in sorted((V1/'RS12').glob('*.lean')):
        rel = path.relative_to(REPO)
        expected = subprocess.check_output(['git','-C',str(REPO),'show',f'{PIN}:{rel}'])
        assert path.read_bytes() == expected, f'Reused source changed: {rel}'
        records.append(dict(path=str(rel),sha256=hashlib.sha256(expected).hexdigest()))
    generated = outputs()
    provenance = dict(base_commit=subprocess.check_output(['git','-C',str(REPO),'rev-parse',PIN]).decode().strip(),
                      source_files=records,
                      generated_files={name:hashlib.sha256(body.encode()).hexdigest() for name,body in generated.items()},
                      witness_leaves=1998, small_blocks=12,
                      transformations='Reference the original proof constants; carry +5 using shifted_sound; join adjacent ranges.')
    generated['provenance.json'] = json.dumps(provenance,indent=2)+'\n'
    for name, body in generated.items():
        path=ROOT/name
        if args.check:
            assert path.read_text() == body, f'Stale adapter or provenance: {name}'
        else:
            path.write_text(body)
    print(f'{"Checked" if args.check else "Wrote"} {len(generated)-1} adapter modules; all {len(records)} reused RS12 modules match {PIN}.')

if __name__ == '__main__':
    main()
