"""Untrusted witness producer. All resulting certificates are checked by Lean's kernel."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
HEADER = '''/-
Copyright (c) 2026 IEANTN contributors. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: IEANTN contributors
-/
'''

def certificates():
    limit = 8192
    prime = bytearray(b'\x01') * (limit + 1)
    prime[:2] = b'\x00\x00'
    for p in range(2, 363):
        if prime[p]:
            for n in range(p*p, limit+1, p):
                prime[n] = 0
    a = 41
    result = []
    while a < limit:
        k = a.bit_length()-2
        L = 3000 if a < 64 else 693*k
        b = min(limit, a + max(1,a//8))
        while True:
            ps = [p for p in range((b+1)//2,a+1) if prime[p]]
            need = (3*b*1000)//(10*L)+1
            if len(ps) >= need:
                break
            assert b > a+1, (a,b,L,len(ps),need)
            b -= 1
        result.append((a,b,k,L,ps[:need]))
        a = b
    return result

def generate():
    rows = certificates()
    output = {}
    # One shard per interval: bounds the memory cost and permits independent builds.
    for i,(a,b,k,L,ps) in enumerate(rows):
        lower = f'log_lower_small {a} (by norm_num)' if a<64 else f'log_lower_dyadic {a} {k} (by norm_num)'
        chunks = [ps[j:j+64] for j in range(0,len(ps),64)]
        data = ''
        for j,chunk in enumerate(chunks):
            data += f"private def block{j} : List ℕ := [{', '.join(map(str,chunk))}]\n"
            data += f"private theorem block{j}_checked : checkPrimes {a} {b} block{j} = true := by decide +kernel\n\n"
        joined = ' ++ '.join(f'block{j}' for j in range(len(chunks)))
        checks = ', '.join(f'block{j}_checked' for j in range(len(chunks)))
        data += f"private def witnesses : List ℕ := {joined}\n\n"
        data += f"private theorem checked : Certificate {a} {b} {L} witnesses := by\n"
        data += "  apply certificate_of_checks (by decide +kernel) ?_ (by decide +kernel)\n"
        extras = ', checkPrimes_append' if len(chunks)>1 else ''
        extras2 = ', Bool.and_self' if len(chunks)>1 else ''
        data += f"  simp only [witnesses{extras}, {checks}{extras2}]\n"

        text = HEADER+f'''import Interval.FiniteCheck

/-! Generated by scripts/generate_finite.py; no computed result is trusted. -/
namespace RSInterval
set_option maxRecDepth 1000000
set_option maxHeartbeats 0

{data}

theorem finite_{i:03d} (x : ℝ) (ha : ({a}:ℝ)/2 ≤ x) (hb : x < ({b}:ℝ)/2) :
    3*x/(5*Real.log x) < IEANTN.primeCounting (2*x) - IEANTN.primeCounting x :=
  certificate_sound (by norm_num) (by norm_num) checked ({lower}) x ha hb

end RSInterval
'''
        output[f'Interval/Data{i:03d}.lean']=text
    text=HEADER+''.join(f'import Interval.Data{i:03d}\n' for i in range(len(rows)))
    text+='''
namespace RSInterval

theorem finite (x : ℝ) (hx : (41:ℝ)/2 ≤ x) (hx' : x < 4096) :
    3*x/(5*Real.log x) < IEANTN.primeCounting (2*x) - IEANTN.primeCounting x := by
'''
    for i,(a,b,*_) in enumerate(rows[:-1]):
        text+=f'''  by_cases h{i} : x < ({b}:ℝ)/2
  · exact finite_{i:03d} x (by linarith) h{i}
'''
    text+=f'''  exact finite_{len(rows)-1:03d} x (by linarith) (by linarith)

end RSInterval
'''
    output['Interval/Finite.lean']=text
    return output,rows

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    output,rows=generate()
    for name,text in output.items():
        p=ROOT/name
        if args.check:
            assert p.read_text()==text, name
        else:
            p.write_text(text)
    print(f'{len(rows)} intervals; {sum(len(r[4]) for r in rows)} prime witnesses; max list {max(len(r[4]) for r in rows)}; endpoints 41/2 to 4096')

if __name__=='__main__': main()
